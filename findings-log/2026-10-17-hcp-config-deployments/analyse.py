#!/usr/bin/env python3
"""analyse.py — lane l2. Zero vendor requests.

Everything the FINDINGS tables state, derived from results.jsonl and the
committed headers/ rather than restated by hand. Re-run it and the tables in
FINDINGS.md can be regenerated; that is the point (AGENTS.md §6.5 — re-derive
prose from the table, never from another prose summary).

Emits analysis.md.
"""
import collections
import hashlib
import json
import os
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
LEDGER = os.path.join(HERE, "results.jsonl")
HDR = os.path.join(HERE, "headers")

rows = [json.loads(l) for l in open(LEDGER, encoding="utf-8") if l.strip()]
# The gate-suite rows are counted in the accounting and then EXCLUDED from every
# analysis below. They are not this pass's sweep: their `t_sent` is a shim's pre-exec
# stamp rather than a stamp taken inside a per-host lock, they carry no body, and two of
# them are on `carelink.medtronic.eu`, a host the sweep also measured — so including
# them would both fake a sub-floor spacing reading and overwrite sweep cells.
gate = [r for r in rows if r.get("kind") == "gate-suite"]
rows = [r for r in rows if r.get("kind") != "gate-suite"]
CLINIC = ["carelinkhp.minimed.eu", "carelink.medtronic.com", "carelink.medtronic.eu"]
SUPPORT = "carelink-support.medtronic.com"
HOSTS = CLINIC + [SUPPORT]

out = ["# analysis.md — every table in FINDINGS.md, machine-derived\n",
       "Generated by `analyse.py` from `results.jsonl` + `headers/`. **Zero vendor "
       "requests.** Do not hand-edit: change the pass and re-run.\n"]

# ---------------------------------------------------------------- 1. request accounting
n = len(rows) + len(gate)
hosts_used = sorted({r["host"] for r in rows})
out.append(f"## 1. Request accounting\n")
out.append(f"- **rows in `results.jsonl`: {n}** = **{len(rows)}** issued by this pass's own "
           f"harness + **{len(gate)}** issued by the repository's pinned assertion suite "
           f"while `./scripts/research-gate.sh` ran (`AGENTS.md` §11 permits re-running "
           f"the suite and nothing else). **The {len(gate)} suite rows are counted and "
           f"excluded from every analysis below** — they carry no body, and their "
           f"`t_sent` is a shim's pre-exec stamp rather than a stamp taken inside a "
           f"per-host lock, so including them would fake a sub-floor spacing reading.")
ghosts = sorted({r["host"] for r in gate})
out.append(f"- gate-suite hosts (counted, not swept): "
           + ", ".join(f"`{h}` ×{sum(1 for r in gate if r['host']==h)}" for h in ghosts))
out.append(f"- hosts contacted: {len(hosts_used)} — {', '.join('`%s`' % h for h in hosts_used)}")
per = collections.Counter(r["host"] for r in rows)
out.append("- rows per host: " + ", ".join(f"`{h}` {per[h]}" for h in hosts_used))
methods = collections.Counter(r["method"] for r in rows)
out.append(f"- methods: {dict(methods)} — GET only, no `-X`, no `-d`, no `Authorization`, "
           f"no `Cookie`, no token exchange, no DNS query, no port scan.\n")

# ---------------------------------------------------------------- 2. spacing
out.append("## 2. Same-host spacing, measured from `t_sent`\n")
gaps = collections.defaultdict(list)
for r in rows:
    if r.get("t_sent"):
        gaps[r["host"]].append(datetime.strptime(r["t_sent"], "%Y-%m-%dT%H:%M:%S.%f%z"
                                                 if r["t_sent"].endswith("Z") is False
                                                 else "%Y-%m-%dT%H:%M:%S.%fZ"))
allg = []
for h in HOSTS:
    ts = sorted(gaps[h])
    if len(ts) < 2:
        out.append(f"- `{h}`: {len(ts)} request(s), no consecutive gap to measure")
        continue
    g = [(ts[i + 1] - ts[i]).total_seconds() for i in range(len(ts) - 1)]
    allg += g
    out.append(f"- `{h}` — {len(ts)} requests, **{len(g)} gaps**, minimum "
               f"**{min(g):.3f} s**, median {sorted(g)[len(g)//2]:.3f} s, "
               f"max {max(g):.3f} s; **{sum(1 for x in g if x >= 2.5)} of {len(g)} at "
               f"or above the declared 2.5 s floor**, {sum(1 for x in g if x < 2.5)} below")
if allg:
    short = [x for x in allg if x < 2.5]
    verdict = (
        "**No cause is asserted for the short reading**, following area A's precedent: a "
        "ledger cannot distinguish a clock step from a delayed process spawn, and the one "
        "gap below the floor is 0.224 s under it."
        if short else "No gap fell below the floor."
    )
    out.append(
        f"\n**Measured `t_sent` floor across every same-host gap in this pass: "
        f"{min(allg):.3f} s over {len(allg)} gaps, {len(short)} below the 2.5 s floor.** "
        f"The floor is enforced by `sleep 2.5` executed **inside** the per-host `flock`, "
        f"not outside it. {verdict}\n"
    )
else:
    out.append("\n**No same-host gap could be measured** — see the note in FINDINGS §2.\n")

# ---- a defect in this pass's own ledger, stated rather than smoothed over ----
badq = [r["seq"] for r in rows if isinstance(r.get("t_queued"), str) and "%3N" in r["t_queued"]]
if badq:
    out.append(f"\n### A defect in this pass's own ledger, on the record\n\n"
               f"**{len(badq)} of {len(rows)} rows carry a `t_queued` and `t_done` that "
               f"contain a literal `%3N`** (seq {badq[0]}–{badq[-1]}). Python's "
               f"`datetime.strftime` does not implement glibc's `%3N`, so the harness "
               f"stamped milliseconds as text in the batch-2 rows. `t_sent` is unaffected: "
               f"it is written by `date -u +%Y-%m-%dT%H:%M:%S.%3NZ` **inside** the flock, "
               f"so it is a real sub-second stamp and it is the field every spacing figure "
               f"above is computed from. The affected `t_queued`/`t_done` values are "
               f"unusable at sub-second resolution and **no figure in this pass depends "
               f"on them**; they are left in place rather than repaired, because "
               f"back-filling a timestamp the process did not record is the one thing a "
               f"ledger must never do (area A's `run.log` caveat).\n")

# ---------------------------------------------------------------- 3. per-host verdicts
KEYS = ["cms-config.json", "cua.control.codes.settings", "cua.crm.settings",
        "hcp.banner.notifications", "logbook.supported.entry.types",
        "personal/media/config", "pow.common.core.report.generation",
        "pow.country.media.groups", "pow.crm.settings", "pow.follow.up.settings",
        "pow.invite.to.personal.uri", "pow.nutrino.cc.broker.service.config",
        "pow.nutrino.cc.metadata.service.config",
        "system.logbook.entry.validation.config",
        "user-identifier-settings?countryCode=EU"]
PFX = "/hcp/configuration/public/"
cell = {}
for r in rows:
    if r["path"].startswith(PFX) and r["sent_headers"] != "(none)":
        cell[(r["host"], r["path"][len(PFX):])] = r

out.append("## 3. The 15 route literals, per host, WITH the header\n")
out.append("Headered cells only. `carelinkhp.minimed.eu` is the 2026-10-08 record, "
           "quoted for comparison; it carries **no cell of its own in this pass** "
           "(only its bundle fetch, seq 1) and is marked as such.\n")
out.append("| route literal | carelinkhp (2026-10-08 record) | carelink.medtronic.com | "
           "carelink.medtronic.eu | carelink-support.medtronic.com | verdict agrees |")
out.append("|---|---|---|---|---|---|")
RECORD = {
    "cms-config.json": "200 application/json 2 B (`{}`)",
    "cua.control.codes.settings": "200 application/json 778 B",
    "cua.crm.settings": "200 application/json 104 B",
    "hcp.banner.notifications": "200 application/json 219 B",
    "logbook.supported.entry.types": "200 application/json 226 B",
    "personal/media/config": "404 0 B",
    "pow.common.core.report.generation": "200 application/json 9863 B",
    "pow.country.media.groups": "200 application/json 768 B",
    "pow.crm.settings": "200 application/octet-stream 96 B",
    "pow.follow.up.settings": "200 application/json 612 B",
    "pow.invite.to.personal.uri": "200 application/json 27 B",
    "pow.nutrino.cc.broker.service.config": "200 application/json 309 B",
    "pow.nutrino.cc.metadata.service.config": "200 application/json 288 B",
    "system.logbook.entry.validation.config": "404 0 B",
    "user-identifier-settings?countryCode=EU": "200 application/json 423 B",
}


def verdict(r):
    if r is None:
        return "**not measured**"
    return f"{r['http_status']} {r['content_type'].split(';')[0]} {r['body_bytes']} B"


agree = 0
for k in KEYS:
    vs = [verdict(cell.get((h, k))) for h in HOSTS]
    codes = {cell[(h, k)]["http_status"] for h in HOSTS if (h, k) in cell}
    ok = len(codes) == 1
    agree += ok
    out.append(f"| `{k}` | {RECORD.get(k,'—')} | {vs[1]} | {vs[2]} | {vs[3]} | "
               f"{'**yes**' if ok else '**NO**'} |")
out.append(f"\n**{agree} of {len(KEYS)} route literals carry the same status verdict on "
           f"all three hosts probed here.** The two hosts absent from the measured "
           f"columns (`carelinkhp.minimed.eu`, and the fourth deployment "
           f"`carelink-support.medtronic.eu`) were not swept and are **not** counted "
           f"in that figure.\n")

# ---------------------------------------------------------------- 4. body equality
out.append("## 4. Same verdict is not the same body — per-key cross-host digest\n")
out.append("| route literal | carelink.medtronic.com | carelink.medtronic.eu | "
           "carelink-support.medtronic.com | byte-identical across hosts |")
out.append("|---|---|---|---|---|")
same, diff, absent = 0, [], []
for k in KEYS:
    hs = []
    for h in HOSTS:
        r = cell.get((h, k))
        hs.append(f"{r['body_bytes']} B `{r['body_sha256'][:12]}…`" if r else "—")
    ds = {cell[(h, k)]["body_sha256"] for h in HOSTS if (h, k) in cell}
    if len(ds) != 1:
        same += 0
        diff.append(k)
    else:
        same += 1
    out.append(f"| `{k}` | {hs[1]} | {hs[2]} | {hs[3]} | "
               f"{'yes' if len(ds)==1 else '**no**'} |")
out.append(f"\n**{same} of {len(KEYS)} keys are byte-identical across all three hosts; "
           f"{len(diff)} differ** — {', '.join('`%s`' % k for k in diff)}.\n")

# ---------------------------------------------------------------- 5. .com vs support
out.append("## 5. The POW/CUA question: clinic `.com` versus the SUPPORT `.com`\n")
com, sup = "carelink.medtronic.com", SUPPORT
ident = []
for k in KEYS:
    a, b = cell.get((com, k)), cell.get((sup, k))
    if a and b:
        ident.append((k, a["body_sha256"] == b["body_sha256"],
                      a["body_sha256"], b["body_sha256"]))
eq = sum(1 for k, s, _, _ in ident if s)
out.append(f"| route literal | clinic `.com` sha256 | support `.com` sha256 | identical |")
out.append("|---|---|---|---|")
for k, s, x, y in ident:
    out.append(f"| `{k}` | `{x[:12]}…` | `{y[:12]}…` | {'yes' if s else '**NO**'} |")
out.append(f"\n**{eq} of {len(ident)} keys are byte-identical between the clinic build's "
           f"deployment and the support build's deployment** — two different "
           f"JavaScript assets (3,397,615 B `2a7fa8e7af519c2b…` against 3,410,666 B "
           f"`a054555a0f22176e…`, both asserted this pass), two different product roles, "
           f"and the entire `hcp/configuration/public/*` namespace answers identically.\n")

# ---------------------------------------------------------------- 6. controls
out.append("## 6. The controls, and what each one proved\n")
out.append("| host | control | path | header | status | bytes | what it proved |")
out.append("|---|---|---|---|---|---:|---|")
CTLS = [
    ("CONTROL-1 positive", "pow.crm.settings", "X-System-ID: ProWeb",
     "`X-System-ID: ProWeb` is ACCEPTED here and the verdict rule is live"),
    ("CONTROL-2 absent", "zzz.this.does.not.exist.zzz", "X-System-ID: ProWeb",
     "a 404 here is distinguishable from the SPA fallback, so a 404 on a key is a true absence"),
    ("CONTROL-3a case, correct spelling", "cua.control.codes.settings", "X-System-ID: ProWeb",
     "the lower-case spelling answers here, so the 3b 404 is about case and not about absence"),
    ("CONTROL-3b case, UPPER spelling", "CSU.CONTROL.CODES.SETTINGS", "X-System-ID: ProWeb",
     "the namespace is CASE-SENSITIVE on this host"),
    ("CONTROL-4 header-absent", "logbook.supported.entry.types", "(none)",
     "412 means 'header rejected at the edge', not 'key absent'"),
]
for h in HOSTS[1:]:
    for label, k, hdrname, why in CTLS:
        rr = next((r for r in rows if r["host"] == h and r["path"] == PFX + k
                   and r["sent_headers"] == (hdrname if hdrname != "(none)" else "(none)")), None)
        out.append(f"| `{h}` | {label} | `{k}` | "
                   f"{'`' + hdrname + '`' if hdrname != '(none)' else '**none sent**'} | "
                   f"{rr['http_status'] if rr else '—'} | {rr['body_bytes'] if rr else '—'} | {why} |")
out.append("")

# ---------------------------------------------------------------- 7. security headers
# Read the COMMITTED response-head files, not the ledger's re-joined `headers`
# string: the two batches joined with different separators (`|` and ` | `), so a
# ledger-derived header set is silently wrong for whichever batch used the other
# one. The files are the artefacts.
out.append("## 7. Response-header asymmetry between the deployments\n")
out.append("Read from the committed `headers/<tag>.h` files, not from the ledger's "
           "`headers` string: the two harness batches joined that field with different "
           "separators, so a ledger-derived header set is silently wrong for whichever "
           "batch used the other one.\n")


def head_set(r):
    p = os.path.join(HDR, r["tag"] + ".h")
    if not os.path.exists(p):
        return set()
    return {l.split(":", 1)[0].strip().lower()
            for l in open(p, errors="replace").read().splitlines() if ":" in l}


WANT = ("content-security-policy", "strict-transport-security",
        "x-frame-options", "x-content-type-options")
HDRSETS = collections.defaultdict(collections.Counter)
tot = collections.Counter()
for r in rows:
    if not r["path"].startswith(PFX):
        continue
    have = head_set(r)
    tot[r["host"]] += 1
    for w in WANT:
        HDRSETS[w][r["host"]] += (1 if w in have else 0)
out.append("| response header | " + " | ".join(f"`{h}`" for h in HOSTS[1:]) + " |")
out.append("|---|" + "---|" * len(HOSTS[1:]))
for w in WANT:
    cells = []
    for h in HOSTS[1:]:
        n = HDRSETS[w][h]
        cells.append(f"{n} of {tot[h]}" if n else f"**0 of {tot[h]}**")
    out.append(f"| `{w}` | " + " | ".join(cells) + " |")
acah = collections.defaultdict(collections.Counter)
for r in rows:
    p = os.path.join(HDR, r["tag"] + ".h")
    if not os.path.exists(p):
        continue
    for l in open(p, errors="replace").read().splitlines():
        if l.lower().startswith("access-control-allow-headers:"):
            acah[r["host"]][l.split(":", 1)[1].strip()] += 1
out.append("")
out.append("| host | `access-control-allow-headers` value | responses |")
out.append("|---|---|---:|")
for h in HOSTS[1:]:
    for v, n in acah[h].most_common():
        out.append(f"| `{h}` | `{v}` | {n} |")
out.append("")

# ---------------------------------------------------------------- 8. redaction note
out.append("## 8. The malformed rows\n")
mal = [r for r in rows if "//" in r["path"]]
canon = {(r["host"], r["path"]): r for r in rows if "//" not in r["path"]
         and r["path"].startswith(PFX)}
out.append(f"| seq | host | path as issued | status | bytes | sha256 | "
           f"canonical twin |")
out.append("|---:|---|---|---|---:|---|---|")
for r in mal:
    t = canon.get((r["host"], r["path"].replace("//", "/")))
    out.append(f"| {r['seq']} | `{r['host']}` | `{r['path']}` | {r['http_status']} | "
               f"{r['body_bytes']} | `{r['body_sha256'][:12]}…` | "
               f"{'seq %d, %s, identical' % (t['seq'], t['body_sha256'][:12]) if t and t['body_sha256'] == r['body_sha256'] else '**differs or absent**'} |")
out.append(f"\n{len(mal)} of {len(rows)} rows carry a malformed path (a doubled slash "
           f"from a trailing slash in a shell variable). They are **left on the ledger "
           f"and counted**, not edited, and none of them is used as one of the 15 "
           f"canonical cells. Observed: the route answers the doubled path with the "
           f"**same status and the same body digest** as the canonical path on all "
           f"{len(mal)} rows — recorded as a routing-normalisation observation, which is "
           f"what AGENTS.md §6.2 warns about being mistaken for a hit.\n")

out.append("## 9. Redaction\n")
out.append("`pow.nutrino.cc.{broker,metadata}.service.config` carried a "
           "**non-placeholder** `security_headers.\"x-api-key\"` on the two `.com` hosts. "
           "The value is **not** in this directory: `redact.py` applied the gate's own "
           "pattern list and `REDACTIONS.md` records the substitution. `results.jsonl`'s "
           "`body_bytes` / `body_sha256` are the **as-received** values and are left "
           "untouched so the finding is reproducible.\n")

open(os.path.join(HERE, "analysis.md"), "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))